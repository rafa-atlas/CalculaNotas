# Apresentação
print("Programa para calcular a média de duas avaliações.")
print("")

# Entrada de dados
nota1 = float(input("Digite a primeira nota: "))
nota2 = float(input("Digite a segunda nota: "))

# Processamento
media = (nota1 + nota2) / 2

# Saída de dados
print(f"A média das avaliações é {media}.")